/**
 * Cap a string for storage and logs.
 *
 * Error text can embed a URL or a server banner, and the status record is shown
 * in the settings page and written on every transition, so it is bounded at the
 * boundary rather than at each call site.
 *
 * @param text - the raw text.
 * @returns the text, clipped when long.
 */
function clip(text: string): string {
  return text.length <= MAX_ERROR_LENGTH ? text : `${text.slice(0, MAX_ERROR_LENGTH - 1)}…`
}

/** Whether a value is a record, narrowed for field inspection. */
function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null
}

/**
 * Compute the next backoff delay.
 *
 * The sequence is 1s, 2s, 4s, 8s, 16s, then 30s forever. It is capped rather
 * than unbounded because a mobile browser throttles a background worker hard,
 * and a delay measured in hours would mean the extension appears permanently
 * dead after a laptop wakes.
 *
 * @param attempt - how many consecutive failures have already happened.
 * @returns the delay in milliseconds, never above {@link MAX_BACKOFF_MS}.
 */
export function backoffDelay(attempt: number): number {
  const safeAttempt = Number.isFinite(attempt) && attempt > 0 ? Math.floor(attempt) : 0
  // Computed by repeated multiplication rather than `2 ** attempt` so that a
  // large attempt count cannot produce `Infinity` before the cap is applied.
  let delay = INITIAL_BACKOFF_MS
  for (let step = 0; step < safeAttempt; step += 1) {
    if (delay >= MAX_BACKOFF_MS) return MAX_BACKOFF_MS
    delay *= BACKOFF_FACTOR
  }
  return Math.min(delay, MAX_BACKOFF_MS)
}

/**
 * Validate a token as the user might have typed it.
 *
 * Whitespace is stripped because copying from a browser page routinely brings a
 * trailing newline with it, and a token that is rejected for an invisible
 * character is indistinguishable to the user from a wrong one. Everything else
 * is the bridge's business: a token with unexpected characters is still sent, so
 * the bridge's own constant-time comparison is what rejects it.
 *
 * @param value - the raw stored value.
 * @returns the usable token, or `null` when there is none.
 */
export function normalizeToken(value: unknown): string | null {
  if (typeof value !== 'string') return null
  const token = value.trim()
  return token === '' ? null : token
}

/**
 * Validate a stored port.
 *
 * @param value - the raw stored value.
 * @returns the port, or {@link DEFAULT_PORT} when absent or unusable.
 */
export function normalizePort(value: unknown): number {
  if (typeof value !== 'number' || !Number.isInteger(value)) return DEFAULT_PORT
  if (value < 1 || value > 65_535) return DEFAULT_PORT
  return value
}

/**
 * Build the socket URL for the bridge.
 *
 * @param port - the loopback port.
 * @returns the URL, e.g. `ws://127.0.0.1:43120`.
 */
export function bridgeUrl(port: number): string {
  return `ws://${BRIDGE_HOST}:${port}`
}

// ---------------------------------------------------------------------------
// Inbound frame narrowing
// ---------------------------------------------------------------------------

/**
 * Narrow one frame from the bridge.
 *
 * The bridge is a local process the user started, which makes it trusted but not
 * omniscient: a version skew or a proxy on the loopback port can put a frame on
 * the wire that this extension does not understand. Unknown frames are ignored
 * rather than treated as fatal, so a newer bridge degrades instead of breaking
 * the older extension.
 *
 * @param value - the result of `JSON.parse` on a frame, or anything else.
 * @returns the narrowed frame, or `undefined`.
 */
export function parseBridgeMessage(value: unknown): BridgeMessage | undefined {
  if (!isRecord(value)) return undefined
  switch (value['type']) {
    case 'welcome': {
      const version = value['version']
      const sessionId = value['sessionId']
      if (typeof version !== 'number') return undefined
      if (sessionId !== null && typeof sessionId !== 'string') return undefined
      return { type: 'welcome', version: version as typeof PROTOCOL_VERSION, sessionId }
    }
    case 'rejected': {
      const reason = value['reason']
      if (reason !== 'token' && reason !== 'version' && reason !== 'rate-limit') return undefined
      return { type: 'rejected', reason }
    }
    case 'pong':
      return { type: 'pong' }
    case 'start-picking': {
      const tabId = value['tabId']
      // `tabId` is optional by design: absent means "whichever tab is in front",
      // which the worker resolves rather than the bridge, because only the
      // extension can see the focused tab.
      if (tabId === undefined) return { type: 'start-picking' }
      if (typeof tabId !== 'number' || !Number.isInteger(tabId)) return undefined
      return { type: 'start-picking', tabId }
    }
    case 'stop-picking':
      return { type: 'stop-picking' }
    case 'submit-ack': {
      const batchId = value['batchId']
      const ok = value['ok']
      const message = value['message']
      if (typeof batchId !== 'string' || typeof ok !== 'boolean') return undefined
      if (message !== undefined && typeof message !== 'string') return undefined
      return message === undefined
        ? { type: 'submit-ack', batchId, ok }
        : { type: 'submit-ack', batchId, ok, message }
    }
    case 'settings': {
      const allowOnline = value['allowOnline']
      if (typeof allowOnline !== 'boolean') return undefined
      return { type: 'settings', allowOnline }
    }
    default:
      return undefined
  }
}

