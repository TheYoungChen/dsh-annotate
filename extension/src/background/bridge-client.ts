/**
 * The extension's connection to the local annotation bridge.
 *
 * The bridge is a loopback WebSocket server owned by the DSH plugin. It accepts
 * exactly one authenticated peer, and the peer proves itself by presenting a
 * bearer token in its very first frame — before that, the server answers nothing
 * and closes on anything else. Everything in this module exists to keep that
 * connection alive, honest and recoverable across the platform's constraints.
 *
 * ## Why this is harder than a normal WebSocket client
 *
 * An MV3 service worker is not a page. It is started to handle an event and
 * stopped when the platform decides it has been idle, and every live object dies
 * with it: the socket, the timers, the in-memory counters. Three consequences
 * shape the design.
 *
 * 1. **Nothing durable may live in a field.** The token, the last error and the
 *    user-visible pairing state are written to `chrome.storage`, and the worker
 *    re-reads what it needs on every start. A field is a cache, never a source
 *    of truth.
 * 2. **A socket cannot outlive the worker, so it is not kept alive by force.**
 *    The alternative — a repeating alarm that pokes the worker often enough to
 *    stop it sleeping — costs the user battery and memory permanently, to
 *    protect a connection that is only needed when the user is actually
 *    annotating. Instead the connection is treated as opportunistic: the worker
 *    dials on start, reconnects with exponential backoff while it happens to be
 *    awake, and the platform's own event delivery is what wakes it for the next
 *    attempt. The one deliberate exception is documented at
 *    {@link REANCHOR_INTERVAL_MS}: while a socket is *open*, the worker holds a
 *    short repeating alarm, because that is precisely the window in which the
 *    user is annotating and a sleep would silently drop their batch.
 * 3. **A batch must never be lost to a sleep.** {@link BridgeClient.sendBatch}
 *    persists the batch before writing it and only clears it on an explicit
 *    acknowledgement, so a worker recycled mid-flight still has the user's work
 *    when it comes back.
 *
 * ## Pairing
 *
 * The token is generated by the DSH side and shown to the user there. The user
 * types it into the extension's settings, which writes it to `chrome.storage`.
 * This module never generates, guesses or defaults a token: an unpaired
 * extension is idle and says so, rather than hammering a server it cannot
 * authenticate against.
 *
 * @module
 */

import {
  DEFAULT_PORT,
  PROTOCOL_VERSION,
  isAnnotationBatch,
  type AnnotationBatch,
  type BridgeMessage,
  type ExtensionMessage,
} from '../../../src/protocol.ts'

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

/** Loopback host the bridge binds. Mirrors the server, which is loopback-only. */
const BRIDGE_HOST = '127.0.0.1'

/** First reconnect delay. Chosen to be short enough to feel instant. */
export const INITIAL_BACKOFF_MS = 1_000

/** Largest reconnect delay. Beyond this a retry storm stops being useful. */
export const MAX_BACKOFF_MS = 30_000

/** Growth factor applied per failed attempt: 1s, 2s, 4s, 8s, then capped. */
const BACKOFF_FACTOR = 2

/**
 * How often the worker re-anchors itself while a socket is open.
 *
 * A worker with an open WebSocket still gets recycled — the socket does not
 * count as activity forever — and a recycled worker takes the socket with it.
 * While the user is annotating that is invisible to them until a batch fails to
 * send, so an open socket is the one state worth spending an alarm on. The
 * period is below the platform's idle threshold, and the alarm is cancelled the
 * moment the socket closes, so the cost is bounded to the annotation session.
 */
export const REANCHOR_INTERVAL_MS = 20_000

/**
 * Liveness probe period.
 *
 * The bridge drops a peer that stops answering, and a laptop that sleeps or a
 * NIC that disappears both produce a socket that looks open long after the peer
 * is gone. Pinging is what turns that into a detectable close.
 */
export const PING_INTERVAL_MS = 25_000

/** Most characters of an error kept for the settings page. */
const MAX_ERROR_LENGTH = 300

