/**
 * The platform capabilities this module needs.
 *
 * Injected rather than reached for directly so the whole connection state
 * machine can be driven in a test harness by a plain object: a service worker
 * cannot be loaded outside a browser, so a module that only works against the
 * real global would be a module with no unit tests.
 */
export interface BridgeEnvironment {
  /** The storage area holding the token, the port and the status record. */
  readonly storage: {
    get(keys: string): Promise<Record<string, unknown>>
    set(items: Record<string, unknown>): Promise<void>
    remove(keys: string | readonly string[]): Promise<void>
  }
  /** Open a socket. Matches the platform constructor's signature. */
  connect(url: string): WebSocketLike
  /** Schedule a wakeup, or clear one when `info` is null. */
  setAlarm(name: string, info: { when: number; periodInMinutes?: number } | null): void
  /** Current wall-clock time, injectable so backoff is testable without waits. */
  now(): number
  /** This extension's id, reported to the bridge for its connection log. */
  extensionId(): string
  /** Timers. Injected so tests control every delay. */
  setTimeout(handler: () => void, ms: number): number
  clearTimeout(handle: number): void
  setInterval(handler: () => void, ms: number): number
  clearInterval(handle: number): void
  /** Log sink. The worker console is the only reader. */
  log(level: 'info' | 'warn' | 'error', message: string): void
}

/**
 * The part of `WebSocket` this module uses.
 *
 * Declared structurally rather than as the DOM interface because a service
 * worker's socket implementation is not guaranteed to be identical, and because
 * a test double made of a plain class is a truer test than one built by
 * patching a global.
 */
export interface WebSocketLike {
  /** Current state, using the platform's numeric encoding. */
  readonly readyState: number
  /** Send one frame. Throws only when the socket is closing. */
  send(data: string): void
  /** Close politely. */
  close(code?: number, reason?: string): void
  /** Fired once the handshake completes. */
  onopen: ((event: unknown) => void) | null
  /** Fired for every inbound frame. */
  onmessage: ((event: { data: unknown }) => void) | null
  /** Fired when the socket closes, for any reason including a refusal. */
  onclose: ((event: unknown) => void) | null
  /** Fired on a transport error. A close normally follows. */
  onerror: ((event: unknown) => void) | null
}

/** `WebSocket.OPEN`, restated so this module needs no DOM global to compile. */
const SOCKET_OPEN = 1

