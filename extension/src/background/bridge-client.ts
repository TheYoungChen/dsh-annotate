/**
 * Owns the single socket to the bridge, and the retry policy around it.
 *
 * One instance per worker lifetime. It is created on the worker's `start()` and
 * its socket dies with the worker; the durable parts of its state are in
 * {@link BridgeEnvironment.storage}, which is what makes a recycled worker pick
 * up where the previous one left off.
 *
 * @example
 * ```ts
 * const client = new BridgeClient({ env, handlers })
 * await client.start()      // reads storage, dials if paired
 * client.sendBatch(batch, tabId)  // persists, then writes
 * ```
 */
export class BridgeClient {
  private readonly env: BridgeEnvironment
  private readonly handlers: BridgeHandlers

  // Everything below is a cache over storage. Losing it is always safe.
  private socket: WebSocketLike | null = null
  /** Frames queued while the handshake is still in flight. */
  private readonly outbox: string[] = []
  /** True once `hello` has been written; frames may now be sent directly. */
  private greeted = false
  /**
   * True once the bridge has accepted the handshake with `welcome`.
   *
   * Distinct from {@link greeted}, which only means the token was sent. Between
   * the two the socket is open but unauthenticated, and treating that window as
   * connected would let a batch be queued as if it were deliverable and let the
   * toolbar badge claim a connection the bridge has not granted.
   */
  private authenticated = false
  /** Suppresses reconnection after a refusal that retrying cannot fix. */
  private halted = false
  /** Token currently in use, refreshed when storage changes. */
  private token: string | null = null
  /** Port currently in use. */
  private port: number = DEFAULT_PORT
  /** Consecutive failed dials, reset by a successful authentication. */
  private attempts = 0
  /** Handle for the pending reconnect timer, so it can be cancelled. */
  private retryTimer: number | null = null
  /** Handle for the liveness ping. */
  private pingTimer: number | null = null
  /** Pending batch keyed by id, so an ack can clear the stored copy. */
  private pendingBatchId: string | null = null
  /** Guards against two dials racing (storage change plus alarm, say). */
  private dialing = false
  /** Set by {@link stop} so a teardown cannot trigger a reconnect. */
  private stopped = false

  /**
   * @param options - the platform seams and the worker's push handlers.
   */
  constructor(options: { env: BridgeEnvironment; handlers: BridgeHandlers }) {
    this.env = options.env
    this.handlers = options.handlers
  }

  // -------------------------------------------------------------------------
  // Lifecycle
  // -------------------------------------------------------------------------

  /**
   * Read durable state and dial if the extension is paired.
   *
   * Safe to call on every worker start: a worker can be started many times for
   * one user action, and a second start while a socket is live is a no-op.
   *
   * @returns a promise that settles once the first dial has been initiated,
   *   which is not the same as connected.
   */
  async start(): Promise<void> {
    this.stopped = false
    await this.reloadConfiguration()
    if (this.token === null) {
      await this.writeStatus('unpaired', 'No pairing token has been entered yet.', null)
      return
    }
    // A refused credential is not retried automatically: the user has to change
    // something first, and a retry loop would only generate noise in the
    // bridge's log while they go and find the right token.
    if (this.halted) return
    this.dial()
  }

  /**
   * Close the socket and cancel every timer.
   *
   * Called when the extension is disabled or the worker is being torn down on
   * purpose. It does NOT clear the token or the pending batch: the next worker
   * start is expected to continue the same session.
   */
  stop(): void {
    this.stopped = true
    this.clearTimers()
    this.env.setAlarm('keepalive', null)
    const socket = this.socket
    this.socket = null
    this.greeted = false
    this.authenticated = false
    this.outbox.length = 0
    if (socket !== null) {
      // Detach before closing so the close handler does not schedule a retry
      // for a shutdown the caller asked for.
      socket.onopen = null
      socket.onmessage = null
      socket.onclose = null
      socket.onerror = null
      try {
        socket.close(1000, 'extension stopping')
      } catch {
        // A socket already closing throws here and there is nothing to do.
      }
    }
  }

  /**
   * Re-read the token and port, applying a change made in the settings page.
   *
   * A changed token always forces a fresh dial, because the old socket was
   * authenticated with a credential that is no longer the current one.
   *
   * @returns a promise that settles after storage has been read.
   */
  async reloadConfiguration(): Promise<void> {
    const stored = await this.env.storage.get(`${STORAGE_KEYS.token}/${STORAGE_KEYS.port}`)
    const token = normalizeToken(stored[STORAGE_KEYS.token])
    const port = normalizePort(stored[STORAGE_KEYS.port])

    const changed = token !== this.token || port !== this.port
    this.token = token
    this.port = port

    if (!changed) return
    // A new credential clears the previous refusal: the user has acted, so the
    // halt condition no longer applies.
    this.halted = false
    this.attempts = 0
    if (token === null) {
      this.handlers.onStopPicking()
      await this.writeStatus('unpaired', 'The pairing token was cleared.', null)
      return
    }
    if (this.socket !== null) {
      // Reconnect rather than re-authenticate: the protocol accepts a `hello`
      // only as the first frame on a fresh socket.
      this.teardownSocket('configuration changed')
    }
    // Dialled unconditionally, including straight after a refusal. A `token`
    // rejection closes the socket itself, so the previous branch is not reached
    // in exactly the case this method exists to serve — the user correcting the
    // token and expecting the extension to notice without a restart.
    this.dial()
  }

  /**
   * Whether the bridge has accepted this extension's handshake.
   *
   * Not the same as "a socket exists": the interval between writing `hello` and
   * receiving `welcome` is one in which the bridge has promised nothing, and
   * callers that gate user-visible behaviour on connectivity must not treat it
   * as connected.
   */
  isConnected(): boolean {
    return this.authenticated && this.socket !== null && this.socket.readyState === SOCKET_OPEN
  }

  /** The port currently in use, for the settings page. */
  currentPort(): number {
    return this.port
  }

  // -------------------------------------------------------------------------
  // Outbound
  // -------------------------------------------------------------------------

  /**
   * Send one batch, persisting it first so a worker recycle cannot lose it.
   *
   * The batch is written to storage before any socket call. If the worker is
   * stopped between the two, the stored copy is still there and
   * {@link retryPending} re-sends it on the next start — which is the difference
   * between a user losing their annotations to a background sleep and not.
   *
   * Delivery has exactly ONE path: the stored record, drained by
   * {@link retryPending}. This method deliberately does not also write the frame
   * directly, because "persist and send" plus "on connect, send whatever is
   * stored" would submit the same batch twice whenever a socket happened to be
   * ready — and duplicated annotations in the conversation are a worse failure
   * than a batch that arrives one round-trip later.
   *
   * @param batch - the validated batch to deliver.
   * @param tabId - the tab it came from, kept for the retry path.
   * @returns a promise that settles once the batch has been persisted and any
   *   delivery attempt for it has been made.
   */
  async sendBatch(batch: AnnotationBatch, tabId: number): Promise<void> {
    const pending: PendingBatch = { batch, tabId, attempts: 0 }
    await this.env.storage.set({ [PENDING_BATCH_KEY]: pending })
    this.pendingBatchId = batch.batchId

    if (this.isConnected()) {
      // Delivered through the stored record so the attempt counter advances and
      // an acknowledgement has something to clear.
      await this.retryPending()
      return
    }
    // Not an error the user has to see: the batch is stored, and the connect
    // path will drain it. The status page shows `reconnecting`.
    this.env.log('warn', `[dsh-annotate] batch ${batch.batchId} stored: no authenticated socket yet`)
  }

  /**
   * Re-send a batch that was persisted but never acknowledged.
   *
   * Called on every worker start. It deliberately does nothing while a socket is
   * still connecting: the batch is already stored, and sending it twice on the
   * same connection would duplicate the annotations in the conversation.
   *
   * @returns a promise that settles once the stored batch has been inspected.
   */
  async retryPending(): Promise<void> {
    if (!this.isConnected()) return
    const stored = await this.env.storage.get(PENDING_BATCH_KEY)
    const pending = readPendingBatch(stored[PENDING_BATCH_KEY])
    if (pending === null) return

    if (pending.attempts >= MAX_BATCH_ATTEMPTS) {
      // Reported once and then dropped: a batch the bridge will not take is not
      // made deliverable by trying forever, and holding it would block every
      // later batch behind it.
      this.env.log('error', `[dsh-annotate] dropping batch ${pending.batch.batchId} after ${pending.attempts} attempts`)
      this.handlers.onBatchRejected(pending.batch.batchId, 'The bridge did not accept this batch after several attempts.')
      await this.clearPending()
      return
    }

    const next: PendingBatch = { batch: pending.batch, tabId: pending.tabId, attempts: pending.attempts + 1 }
    await this.env.storage.set({ [PENDING_BATCH_KEY]: next })
    this.pendingBatchId = pending.batch.batchId
    this.write({ type: 'submit', batch: pending.batch })
  }

  /**
   * Announce the page the user is annotating.
   *
   * Best-effort by design: the bridge uses this only to title its own log, and a
   * dropped announcement has no bearing on whether annotations arrive.
   *
   * @param tabId - the tab id.
   * @param url - the page URL.
   * @param title - the page title.
   */
  announcePage(tabId: number, url: string, title: string): void {
    this.write({ type: 'page-picked', tabId, url, title })
  }

  /**
   * Send a liveness probe.
   *
   * The protocol has no client-side `pong`, so the bridge treats any inbound
   * frame as proof of life; a ping is the cheapest such frame.
   */
  ping(): void {
    this.write({ type: 'ping' })
  }

  // -------------------------------------------------------------------------
  // Connection
  // -------------------------------------------------------------------------

  /** Open a socket and arm its handlers. */
  private dial(): void {
    if (this.stopped || this.halted || this.dialing) return
    if (this.socket !== null) return
    if (this.token === null) return

    this.dialing = true
    const url = bridgeUrl(this.port)
    this.env.log('info', `[dsh-annotate] dialling ${url}`)

    let socket: WebSocketLike
    try {
      socket = this.env.connect(url)
    } catch (error: unknown) {
      // A malformed URL or a blocked scheme throws synchronously. Treated as a
      // failed attempt so the backoff sequence still runs.
      this.dialing = false
      void this.scheduleRetry(error instanceof Error ? error.message : String(error), 'connecting')
      return
    }

    this.socket = socket
    this.greeted = false
    this.authenticated = false
    void this.writeStatus(this.attempts === 0 ? 'connecting' : 'reconnecting', null, null)

    socket.onopen = () => {
      this.dialing = false
      // The handshake is the one place the token is sent. It goes first, before
      // anything else, because the bridge closes a socket that speaks out of
      // turn rather than answering an unauthenticated frame.
      this.greeted = true
      this.sendNow({
        type: 'hello',
        version: PROTOCOL_VERSION,
        token: this.token ?? '',
        extensionId: this.env.extensionId(),
      })
    }

    socket.onmessage = (event) => {
      const text = typeof event.data === 'string' ? event.data : ''
      if (text === '') return
      this.handleFrame(text)
    }

    socket.onerror = () => {
      // An error is always followed by a close, which is where the retry is
      // scheduled; logging here would double every failure.
      this.env.log('warn', '[dsh-annotate] socket error')
    }

    socket.onclose = (event) => {
      this.dialing = false
      const code = closeCodeOf(event)
      // Whether the handshake got as far as a `hello`. This decides which story
      // the user is told: "the bridge is not running" and "the bridge hung up on
      // us" are different problems with different fixes.
      const wasGreeted = this.greeted
      this.socket = null
      this.greeted = false
      this.authenticated = false
      this.outbox.length = 0
      this.clearPing()
      // Released here as well as in teardown: the keepalive alarm exists to hold
      // the worker awake for an OPEN socket, so leaving it armed after a drop
      // would pin the worker awake permanently to protect nothing.
      this.env.setAlarm('keepalive', null)

      if (this.stopped) return
      // The bridge's own close codes distinguish "you are not who you say" from
      // "the network went away". Only the first is worth telling the user about;
      // the second is handled by reconnecting, which is what they actually want.
      if (this.halted) return
      const detail = wasGreeted
        ? `The bridge closed the connection${code === null ? '' : ` (code ${code})`}.`
        : 'The bridge is not reachable on its loopback port.'
      void this.scheduleRetry(detail, 'reconnecting')
    }
  }

  /**
   * Route one authenticated frame.
   *
   * @param text - the decoded frame.
   */
  private handleFrame(text: string): void {
    let parsed: unknown
    try {
      parsed = JSON.parse(text)
    } catch {
      this.env.log('warn', '[dsh-annotate] dropped an unparseable frame from the bridge')
      return
    }

    const message = parseBridgeMessage(parsed)
    if (message === undefined) {
      // Forward compatibility: a newer bridge may send frames this build does
      // not know, and dropping them keeps the connection usable.
      this.env.log('warn', '[dsh-annotate] ignored an unrecognised frame from the bridge')
      return
    }

    switch (message.type) {
      case 'welcome':
        void this.onWelcome(message.version)
        break
      case 'rejected':
        void this.onRejected(message.reason)
        break
      case 'submit-ack':
        void this.onSubmitAck(message.batchId, message.ok, message.message)
        break
      case 'start-picking':
        this.handlers.onStartPicking(message.tabId ?? null)
        break
      case 'stop-picking':
        this.handlers.onStopPicking()
        break
      case 'settings':
        this.handlers.onAllowOnline(message.allowOnline)
        break
      case 'pong':
        // Liveness is proven by the frame arriving; there is nothing to record.
        break
    }
  }

  /**
   * Apply a successful authentication.
   *
   * @param version - the protocol version the bridge reported.
   */
  private async onWelcome(version: number): Promise<void> {
    // The backoff is reset only here, not on every socket open: a server that
    // accepts connections and then refuses them would otherwise be dialled once
    // per second forever.
    this.attempts = 0
    this.halted = false
    this.authenticated = true
    await this.writeStatus('connected', null, version)

    // Anything that queued while the handshake was in flight goes out now, in
    // the order it was produced.
    const queued = this.outbox.splice(0, this.outbox.length)
    for (const frame of queued) this.sendRaw(frame)

    this.startPing()
    // The socket is the state worth paying for: see {@link REANCHOR_INTERVAL_MS}.
    this.env.setAlarm('keepalive', { when: this.env.now() + REANCHOR_INTERVAL_MS, periodInMinutes: REANCHOR_INTERVAL_MS / 60_000 })

    await this.retryPending()
  }

  /**
   * Apply a refusal.
   *
   * The three reasons are genuinely different situations for the user, so they
   * are not collapsed into one "connection failed" state:
   *
   * - `token`: the user pasted the wrong value. Retrying is pointless and would
   *   bury the fix behind an endless reconnect loop, so the client halts and
   *   says what to do.
   * - `version`: the extension and the plugin are not from the same release.
   *   Also halted, because no retry can change a build.
   * - `rate-limit`: temporary by definition. Backoff continues, more slowly.
   *
   * @param reason - the reason the bridge gave.
   */
  private async onRejected(reason: RejectReason): Promise<void> {
    this.clearTimers()

    if (reason === 'token') {
      this.halted = true
      this.teardownSocket('token rejected')
      await this.writeStatus('unauthorized', 'The bridge rejected the pairing token. Copy the current token from the DSH plugin settings and paste it here again.', null)
      return
    }
    if (reason === 'version') {
      this.halted = true
      this.teardownSocket('protocol mismatch')
      await this.writeStatus('incompatible', `The bridge speaks a different protocol version than this extension (extension v${PROTOCOL_VERSION}). Update the extension and the DSH plugin together.`, null)
      return
    }

    this.teardownSocket('rate limited')
    void this.scheduleRetry('The bridge is rate-limiting this extension.', 'reconnecting')
  }

  /**
   * Finish a batch submission.
   *
   * @param batchId - the acknowledged batch.
   * @param ok - whether the bridge accepted it.
   * @param message - the bridge's explanation when it did not.
   */
  private async onSubmitAck(batchId: string, ok: boolean, message: string | undefined): Promise<void> {
    if (this.pendingBatchId === batchId) {
      this.pendingBatchId = null
      await this.clearPending()
    }
    if (ok) {
      this.handlers.onBatchAcked(batchId)
      const current = await this.readStatus()
      await this.env.storage.set({
        [STORAGE_KEYS.status]: { ...current, batchesAcked: current.batchesAcked + 1, updatedAt: this.env.now() },
      })
      return
    }
    this.handlers.onBatchRejected(batchId, message ?? 'The bridge refused the batch.')
  }

  /**
   * Record a failure and schedule the next dial.
   *
   * @param detail - what to show the user.
   * @param state - the state to report while waiting.
   */
  private async scheduleRetry(detail: string, state: ConnectionState): Promise<void> {
    if (this.stopped || this.halted) return
    if (this.retryTimer !== null) return

    // `attempts` counts failures that have already happened, and it is read
    // BEFORE this one is counted so that the first failure waits the first
    // delay. Incrementing first would make the very first retry wait twice as
    // long as intended, and every subsequent one along with it.
    const delay = backoffDelay(this.attempts)
    this.attempts += 1
    const at = this.env.now() + delay

    // The timer is installed BEFORE the status write is awaited. Persisting the
    // status is asynchronous, and a second failure arriving in that window would
    // otherwise see `retryTimer` still null and install a competing timer, which
    // would double the dial rate instead of backing it off.
    this.retryTimer = this.env.setTimeout(() => {
      this.retryTimer = null
      this.dial()
    }, delay)
    this.env.setAlarm('reconnect', { when: at })
    this.env.log('info', `[dsh-annotate] reconnecting in ${delay}ms (attempt ${this.attempts})`)

    // The timer covers the case where the worker is still awake, which is the
    // common one: a bridge restart takes a second, not twenty. The alarm covers
    // the case where it is not.
    await this.writeStatus(state, clip(detail), null, at)
  }

  // -------------------------------------------------------------------------
  // Socket plumbing
  // -------------------------------------------------------------------------

  /**
   * Write a frame, queueing it until the handshake has completed.
   *
   * The queue exists because the interesting frames are produced by the user's
   * click, and a click can land in the few milliseconds between the socket
   * opening and the bridge confirming the handshake. Dropping those frames would
   * mean the first annotation of a session is the one that goes missing.
   *
   * @param message - the frame to write.
   * @returns whether it was written immediately.
   */
  private write(message: ExtensionMessage): boolean {
    const frame = JSON.stringify(message)
    if (!this.greeted || this.socket === null || this.socket.readyState !== SOCKET_OPEN) {
      // Bounded: a queue that grows without a connected socket would grow with
      // every pick the user makes while the bridge is down.
      if (this.outbox.length < 16) this.outbox.push(frame)
      return false
    }
    this.sendRaw(frame)
    return true
  }

  /**
   * Write a frame to a socket known to be open.
   *
   * @param frame - the serialised frame.
   */
  private sendRaw(frame: string): void {
    const socket = this.socket
    if (socket === null || socket.readyState !== SOCKET_OPEN) return
    try {
      socket.send(frame)
    } catch (error: unknown) {
      // A send on a socket that closed between the state check and the call.
      // The close handler owns the reconnect, so this only reports.
      this.env.log('warn', `[dsh-annotate] send failed: ${error instanceof Error ? error.message : String(error)}`)
    }
  }

  /** Write a frame without queueing, for the handshake itself. */
  private sendNow(message: ExtensionMessage): void {
    this.sendRaw(JSON.stringify(message))
  }

  /**
   * Detach and close the socket without scheduling a retry.
   *
   * @param reason - the close reason sent to the bridge.
   */
  private teardownSocket(reason: string): void {
    const socket = this.socket
    this.socket = null
    this.greeted = false
    this.authenticated = false
    this.outbox.length = 0
    this.clearPing()
    this.env.setAlarm('keepalive', null)
    if (socket === null) return
    socket.onopen = null
    socket.onmessage = null
    socket.onclose = null
    socket.onerror = null
    try {
      socket.close(1000, reason)
    } catch {
      // Nothing to do: the socket is already gone.
    }
  }

  /** Start the liveness probe. */
  private startPing(): void {
    this.clearPing()
    this.pingTimer = this.env.setInterval(() => { this.ping() }, PING_INTERVAL_MS)
  }

  /** Stop the liveness probe. */
  private clearPing(): void {
    if (this.pingTimer === null) return
    this.env.clearInterval(this.pingTimer)
    this.pingTimer = null
  }

  /** Cancel every timer this client owns. */
  private clearTimers(): void {
    if (this.retryTimer !== null) {
      this.env.clearTimeout(this.retryTimer)
      this.retryTimer = null
    }
    this.clearPing()
  }

  // -------------------------------------------------------------------------
  // Durable state
  // -------------------------------------------------------------------------

  /**
   * Read the status record, falling back to the initial one.
   *
   * @returns the stored status, or {@link INITIAL_STATUS}.
   */
  private async readStatus(): Promise<BridgeStatus> {
    const stored = await this.env.storage.get(STORAGE_KEYS.status)
    return readStatusRecord(stored[STORAGE_KEYS.status])
  }

  /**
   * Merge a transition into the status record and persist it.
   *
   * Every field is written on every transition rather than patched, because the
   * previous record may be from an older build of the extension and a partial
   * update would leave the settings page rendering a shape that no longer
   * exists.
   *
   * @param state - the new connection state.
   * @param detail - explanation for the user, already bounded.
   * @param bridgeVersion - the bridge's protocol version, when known.
   * @param nextAttemptAt - when the next dial is due, when one is scheduled.
   */
  private async writeStatus(
    state: ConnectionState,
    detail: string | null,
    bridgeVersion: number | null,
    nextAttemptAt: number | null = null,
  ): Promise<void> {
    const now = this.env.now()
    const previous = await this.readStatus()
    const status: BridgeStatus = {
      state,
      detail,
      connectedAt: state === 'connected' ? now : previous.connectedAt,
      nextAttemptAt,
      attempts: this.attempts,
      bridgeVersion: bridgeVersion ?? previous.bridgeVersion,
      batchesAcked: previous.batchesAcked,
      updatedAt: now,
    }
    await this.env.storage.set({ [STORAGE_KEYS.status]: status })
  }

  /** Drop the stored in-flight batch. */
  private async clearPending(): Promise<void> {
    await this.env.storage.remove(PENDING_BATCH_KEY)
  }
}

/**
 * Read the close code out of a close event.
 *
 * The event is typed as unknown because the platform's `CloseEvent` is not
 * guaranteed present in a worker's lib set; the code is the only field used, and
 * an absent one is reported as absent rather than as zero.
 *
 * @param event - the close event.
 * @returns the close code, or `null`.
 */
function closeCodeOf(event: unknown): number | null {
  if (!isRecord(event)) return null
  const code = event['code']
  return typeof code === 'number' ? code : null
}

/**
 * Recover a pending batch from storage.
 *
 * The stored value is validated rather than trusted: it was written by an
 * earlier build of this extension, and a shape change must degrade to "no
 * pending batch" instead of throwing inside a worker start.
 *
 * @param value - the raw stored value.
 * @returns the pending batch, or `null`.
 */
export function readPendingBatch(value: unknown): PendingBatch | null {
  if (!isRecord(value)) return null
  const attempts = value['attempts']
  const tabId = value['tabId']
  if (typeof attempts !== 'number' || !Number.isInteger(attempts) || attempts < 0) return null
  if (typeof tabId !== 'number' || !Number.isInteger(tabId)) return null
  const batch = value['batch']
  // The protocol's own guard runs here, not a local restatement of it: a stored
  // batch that no longer validates is dropped now rather than sent and refused
  // by the bridge, and using the same predicate means the two can never drift.
  if (!isAnnotationBatch(batch)) return null
  return { batch, tabId, attempts }
}

/**
 * Recover a status record from storage.
 *
 * @param value - the raw stored value.
 * @returns the record, or {@link INITIAL_STATUS} when it is missing or unusable.
 */
export function readStatusRecord(value: unknown): BridgeStatus {
  if (!isRecord(value)) return INITIAL_STATUS
  const state = value['state']
  if (!isConnectionState(state)) return INITIAL_STATUS
  const detail = value['detail']
  const connectedAt = value['connectedAt']
  const nextAttemptAt = value['nextAttemptAt']
  const attempts = value['attempts']
  const bridgeVersion = value['bridgeVersion']
  const batchesAcked = value['batchesAcked']
  const updatedAt = value['updatedAt']
  return {
    state,
    detail: typeof detail === 'string' ? detail : null,
    connectedAt: typeof connectedAt === 'number' ? connectedAt : null,
    nextAttemptAt: typeof nextAttemptAt === 'number' ? nextAttemptAt : null,
    attempts: typeof attempts === 'number' ? attempts : 0,
    bridgeVersion: typeof bridgeVersion === 'number' ? bridgeVersion : null,
    batchesAcked: typeof batchesAcked === 'number' ? batchesAcked : 0,
    updatedAt: typeof updatedAt === 'number' ? updatedAt : 0,
  }
}

/**
 * Whether a value is one of the connection states.
 *
 * @param value - candidate state.
 * @returns whether it is a known state.
 */
export function isConnectionState(value: unknown): value is ConnectionState {
  return value === 'unpaired'
    || value === 'connecting'
    || value === 'connected'
    || value === 'reconnecting'
    || value === 'unauthorized'
    || value === 'incompatible'
}

/**
 * A human sentence describing a state, for the settings page and the badge.
 *
 * @param status - the record to describe.
 * @returns a short, secret-free description.
 */
export function describeStatus(status: BridgeStatus): string {
  switch (status.state) {
    case 'unpaired':
      return 'Not paired. Paste the token from the DSH plugin settings to connect.'
    case 'connecting':
      return 'Connecting to the local bridge…'
    case 'connected':
      return 'Connected. Picking is available.'
    case 'reconnecting':
      return status.detail ?? 'Reconnecting to the local bridge…'
    case 'unauthorized':
      return status.detail ?? 'The bridge rejected the pairing token.'
    case 'incompatible':
      return status.detail ?? 'The extension and the bridge speak different protocol versions.'
  }
}
