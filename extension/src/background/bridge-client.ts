/** Storage keys. Exported so the settings page writes exactly what is read. */
export const STORAGE_KEYS = {
  /** Bearer token the user copied out of DSH. */
  token: 'bridge.token',
  /** Bridge port, so a DSH instance on a non-default port still works. */
  port: 'bridge.port',
  /** Worker health, written for the settings page to read. */
  status: 'bridge.status',
} as const

/** Connection health, as the settings page shows it. */
export type ConnectionState =
  /** No usable token has been entered, so nothing is dialled. */
  | 'unpaired'
  /** A dial is in flight. */
  | 'connecting'
  /** Authenticated and idle. */
  | 'connected'
  /** A dial is scheduled or the socket dropped; a retry is coming. */
  | 'reconnecting'
  /** The bridge refused the token. Retrying cannot help until the user fixes it. */
  | 'unauthorized'
  /** The bridge speaks a different protocol. Retrying cannot help either. */
  | 'incompatible'

/** Why the bridge refused the connection. Mirrors `rejected.reason`. */
export type RejectReason = 'token' | 'version' | 'rate-limit'

/** The worker health record, persisted so it survives a recycle. */
export interface BridgeStatus {
  readonly state: ConnectionState
  /** Human-readable explanation, already bounded and free of secrets. */
  readonly detail: string | null
  /** When the last successful authentication happened, or null. */
  readonly connectedAt: number | null
  /** When the next dial is due, or null when none is scheduled. */
  readonly nextAttemptAt: number | null
  /** How many consecutive failures preceded the current state. */
  readonly attempts: number
  /** Protocol version the bridge reported, or null when unknown. */
  readonly bridgeVersion: number | null
  /** Batches accepted by the bridge since this worker's storage was written. */
  readonly batchesAcked: number
  /** When this record was last written, so a stale one is recognisable. */
  readonly updatedAt: number
}

/** The status a never-started worker reports. */
export const INITIAL_STATUS: BridgeStatus = {
  state: 'unpaired',
  detail: null,
  connectedAt: null,
  nextAttemptAt: null,
  attempts: 0,
  bridgeVersion: null,
  batchesAcked: 0,
  updatedAt: 0,
}

/**
 * A batch awaiting acknowledgement, kept in storage rather than in memory.
 *
 * Only one is held. A queue would have to answer "in what order do two failed
 * batches from two tabs reach the conversation", and that is a product decision
 * this module is not entitled to make; holding the newest batch and letting the
 * user see the failure is the honest behaviour.
 */
export interface PendingBatch {
  readonly batch: AnnotationBatch
  /** The tab the batch came from, so the retry reuses the right frame tree. */
  readonly tabId: number
  /** How many times a write has been attempted, to bound the retrying. */
  readonly attempts: number
}

/** Storage key for the in-flight batch. */
const PENDING_BATCH_KEY = 'bridge.pending'

/** Most times one batch is re-sent before it is reported as undeliverable. */
export const MAX_BATCH_ATTEMPTS = 5

